"""Calibrate a detector threshold on texts whose origin you know.

    uv run calibrate.py --human human_dir --ai ai_dir --out calibration.json
                        [--method binoculars|fastdetect|desklib] [--size medium] [--target-fpr 0.05]
                        [--scores-only scores.json]   # re-use scores from an earlier run

human_dir: files (.docx/.pdf/.md/.tex/.txt) you are sure were written by people - e.g. the candidate's
           own papers from before 2022, or chapters written without any assistant.
ai_dir:    files you are sure were produced by a language model - e.g. 20-40 paragraphs generated by
           Claude/ChatGPT on the same topic and in the same language/register (see SKILL.md).

Every file is chunked like detect_ai.py does, every chunk is scored, and the script reports AUROC,
the threshold that keeps the false-positive rate (human chunks flagged) at --target-fpr, and the
threshold at 1 % FPR, plus the recall each threshold achieves on the AI chunks. The output JSON is
what detect_ai.py --calibration consumes. With fewer than ~30 chunks per class the numbers are noisy;
the script says so.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import math
import sys
from pathlib import Path

import text_common as tc
from ai_models import DIRECTION, METHODS, PAIRS, build


def collect(dir_: Path, chunk_words: int) -> list[dict]:
    out: list[dict] = []
    files = sorted(p for p in dir_.rglob("*") if p.is_file() and p.suffix.lower() in tc.SUPPORTED)
    for f in files:
        try:
            doc = tc.extract(f)
        except tc.ExtractError as exc:
            print(f"skip {f}: {exc}", file=sys.stderr)
            continue
        for c in tc.chunks_by_words(doc.body() or doc.paragraphs, target_words=chunk_words):
            c["file"] = f.name
            out.append(c)
    return out


def auroc(pos: list[float], neg: list[float]) -> float:
    """Probability that a random AI score ranks above a random human score (ties count half)."""
    if not pos or not neg:
        return float("nan")
    wins = 0.0
    for p in pos:
        for n in neg:
            wins += 1.0 if p > n else 0.5 if p == n else 0.0
    return wins / (len(pos) * len(neg))


def threshold_at_fpr(human: list[float], ai: list[float], direction: int, target: float) -> tuple[float, float, float]:
    """Return (threshold, achieved_fpr, recall) with scores oriented so that higher = more AI-like."""
    h = sorted(human)
    n = len(h)
    k = int(math.floor(target * n))              # number of human chunks allowed above the threshold
    cut = h[n - 1 - k] if k < n else h[0]
    # threshold is just above the (n-k)-th human score -> flag everything strictly greater
    th = math.nextafter(cut, math.inf)
    fpr = sum(1 for x in h if x >= th) / n
    recall = sum(1 for x in ai if x >= th) / max(1, len(ai))
    return th, fpr, recall


def orient(method: str, x: float) -> float:
    return x * DIRECTION[method]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--human", type=Path)
    ap.add_argument("--ai", type=Path)
    ap.add_argument("--out", type=Path, default=Path("calibration.json"))
    ap.add_argument("--method", default="binoculars", choices=METHODS)
    ap.add_argument("--size", default="medium", choices=sorted(PAIRS))
    ap.add_argument("--observer")
    ap.add_argument("--performer")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--chunk-words", type=int, default=220)
    ap.add_argument("--max-tokens", type=int, default=512)
    ap.add_argument("--target-fpr", type=float, default=0.05)
    ap.add_argument("--scores-only", type=Path, help="JSON with {'human': [...], 'ai': [...], 'models': [...]} to skip scoring")
    args = ap.parse_args(argv)

    if args.scores_only:
        data = json.loads(args.scores_only.read_text(encoding="utf-8"))
        human, ai, models = data["human"], data["ai"], data.get("models", [])
    else:
        if not (args.human and args.ai):
            ap.error("--human and --ai are required unless --scores-only is given")
        hc, ac = collect(args.human, args.chunk_words), collect(args.ai, args.chunk_words)
        if not hc or not ac:
            print("ERROR: no scorable chunks in one of the folders", file=sys.stderr)
            return 2
        scorer = build(args.method, size=args.size, observer=args.observer, performer=args.performer, device=args.device)
        models = scorer.models()
        human = [scorer.score(c["text"], args.max_tokens).score for c in hc]
        ai = [scorer.score(c["text"], args.max_tokens).score for c in ac]
        human = [x for x in human if not math.isnan(x)]
        ai = [x for x in ai if not math.isnan(x)]
        (args.out.with_suffix(".scores.json")).write_text(json.dumps({"method": args.method, "models": models, "human": human,
                                                                       "ai": ai}, indent=1), encoding="utf-8")

    oh = [orient(args.method, x) for x in human]
    oa = [orient(args.method, x) for x in ai]
    au = auroc(oa, oh)
    th, fpr, rec = threshold_at_fpr(oh, oa, +1, args.target_fpr)
    th1, fpr1, rec1 = threshold_at_fpr(oh, oa, +1, 0.01)
    result = {
        "method": args.method, "models": models, "date": dt.date.today().isoformat(),
        "n_human_chunks": len(human), "n_ai_chunks": len(ai), "auroc": au,
        "target_fpr": args.target_fpr, "threshold": th * DIRECTION[args.method], "achieved_fpr": fpr, "recall": rec,
        "threshold_fpr01": th1 * DIRECTION[args.method], "achieved_fpr01": fpr1, "recall_fpr01": rec1,
        "direction": "lower = AI" if DIRECTION[args.method] < 0 else "higher = AI",
        "warning": ("fewer than 30 chunks per class: thresholds are noisy" if min(len(human), len(ai)) < 30 else ""),
    }
    args.out.write_text(json.dumps({args.method: result}, indent=1), encoding="utf-8")
    print(f"{args.method} {models}: AUROC={au:.3f}  human={len(human)} ai={len(ai)} chunks")
    print(f"threshold@FPR{args.target_fpr:.0%}: {result['threshold']:.4f} (achieved FPR {fpr:.1%}, recall {rec:.1%})")
    print(f"threshold@FPR1%:  {result['threshold_fpr01']:.4f} (achieved FPR {fpr1:.1%}, recall {rec1:.1%})")
    if result["warning"]:
        print("WARNING:", result["warning"])
    if au < 0.8:
        print("WARNING: AUROC < 0.8 - this detector barely separates your human and AI samples; do not rely on its verdicts.")
    print(f"Wrote {args.out.resolve()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
